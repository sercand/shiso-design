// Generates every platform's tokens from tokens/tokens.json. No dependencies.
//   packages/css/tokens.css        CSS variables (light, dark, density)
//   packages/tailwind/theme.css    Tailwind v4 theme + shadcn variable names
//   packages/native/src/tokens.ts  React Native
//   crates/shiso-theme/src/tokens.rs  Rust
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));
const HEADER = "Generated by scripts/build.mjs from tokens/tokens.json. Do not edit.";

// OKLCH -> sRGB (gamut-mapped by reducing chroma), for platforms without OKLCH.
function oklchToLinear([l, c, h]) {
  const a = c * Math.cos((h * Math.PI) / 180);
  const b = c * Math.sin((h * Math.PI) / 180);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
}
const inGamut = (rgb) => rgb.every((v) => v >= -0.0005 && v <= 1.0005);
function toRgb(lch) {
  let [l, c, h] = lch;
  let lin = oklchToLinear([l, c, h]);
  for (let i = 0; i < 40 && !inGamut(lin); i++) {
    c *= 0.95;
    lin = oklchToLinear([l, c, h]);
  }
  return lin.map((v) => {
    v = Math.min(1, Math.max(0, v));
    const s = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.round(s * 255);
  });
}
const hex = (lch) => "#" + toRgb(lch).map((v) => v.toString(16).padStart(2, "0")).join("");
const oklch = ([l, c, h]) => `oklch(${l} ${c} ${h})`;
const clean = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith("$")));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
const upper = (s) => s.replace(/-/g, "_").toUpperCase();

const light = t.color.light;
const dark = t.color.dark;
const text = clean(t.text);
const density = clean(t.density);
const shadowLight = t.shadow.light
  .map((s) => `0 ${s.y}px ${s.blur}px ${s.spread}px oklch(${light.text[0]} ${light.text[1]} ${light.text[2]} / ${s.alpha})`)
  .join(", ");
const shadowDark = `0 0 0 1px oklch(1 0 0 / ${t.shadow["dark-ring-alpha"]})`;

// ---------- CSS ----------
const colorVars = (set, indent) =>
  Object.entries(set).map(([k, v]) => `${indent}--shiso-${k}: ${oklch(v)};`).join("\n");
const densityVars = (d, indent) =>
  [`--shiso-control: ${d.control}px;`, `--shiso-text-base: ${d.text}px;`, `--shiso-pad: ${d.pad}px;`, `--shiso-gap: ${d.gap}px;`]
    .map((l) => indent + l)
    .join("\n");
const darkBlock = (sel, indent) =>
  `${indent}${sel} {\n${colorVars(dark, indent + "  ")}\n${indent}  --shiso-shadow: ${shadowDark};\n${indent}  color-scheme: dark;\n${indent}}`;

const css = `/* ${HEADER} */
:root {
${colorVars(light, "  ")}
  --shiso-shadow: ${shadowLight};

  --shiso-font-sans: "${t.font.sans}", ${t.font["sans-fallback"]};
  --shiso-font-mono: "${t.font.mono}", ${t.font["mono-fallback"]};
${Object.entries(t.weight).map(([k, v]) => `  --shiso-weight-${k}: ${v};`).join("\n")}
${Object.entries(text).map(([k, v]) => `  --shiso-text-${k}: ${v}px;`).join("\n")}
${Object.entries(t.radius).map(([k, v]) => `  --shiso-radius-${k}: ${v}px;`).join("\n")}
${Object.entries(t.space).map(([k, v]) => `  --shiso-space-${k}: ${v}px;`).join("\n")}
${densityVars(density.compact, "  ")}
  color-scheme: light;
}
[data-density="comfortable"] {
${densityVars(density.comfortable, "  ")}
}
[data-density="compact"] {
${densityVars(density.compact, "  ")}
}
/* Dark: follows the system unless data-theme pins a mode; .dark is the shadcn/next-themes class. */
@media (prefers-color-scheme: dark) {
${darkBlock(':root:not([data-theme="light"]):not(.light)', "  ")}
}
${darkBlock(':root[data-theme="dark"], .dark', "")}
`;
writeFileSync(join(root, "packages/css/tokens.css"), css);

// ---------- Tailwind v4 + shadcn names ----------
const shadcn = {
  background: "canvas", foreground: "text", card: "card", "card-foreground": "text",
  popover: "card", "popover-foreground": "text", primary: "primary", "primary-foreground": "primary-text",
  secondary: "fill", "secondary-foreground": "text", muted: "fill", "muted-foreground": "text-2",
  accent: "fill", "accent-foreground": "text", destructive: "bad", border: "line", input: "line", ring: "primary",
  sidebar: "canvas", "sidebar-foreground": "text", "sidebar-primary": "primary", "sidebar-primary-foreground": "primary-text",
  "sidebar-accent": "card", "sidebar-accent-foreground": "text", "sidebar-border": "line", "sidebar-ring": "primary",
};
const tw = `/* ${HEADER} */
/* Usage: @import "tailwindcss"; @import "@shiso/design/css/tokens.css"; @import "@shiso/design/tailwind/theme.css"; */
:root {
${Object.entries(shadcn).map(([k, v]) => `  --${k}: var(--shiso-${v});`).join("\n")}
  --radius: var(--shiso-radius-control);
}
@theme inline {
  --font-sans: var(--shiso-font-sans);
  --font-heading: var(--shiso-font-sans);
  --font-mono: var(--shiso-font-mono);
${Object.keys(shadcn).map((k) => `  --color-${k}: var(--${k});`).join("\n")}
${Object.keys(light).map((k) => `  --color-shiso-${k}: var(--shiso-${k});`).join("\n")}
  /* Radius: one step per role. Everything from 2xl up is the card radius, so legacy large radii stay soft. */
  --radius-sm: var(--shiso-radius-sm);
  --radius-md: 8px;
  --radius-lg: var(--shiso-radius-control);
  --radius-xl: 12px;
  --radius-2xl: var(--shiso-radius-card);
  --radius-3xl: var(--shiso-radius-card);
  --radius-4xl: var(--shiso-radius-card);
  --radius-control: var(--shiso-radius-control);
  --radius-card: var(--shiso-radius-card);
  /* Density: h-control / size-control follow data-density; text-sm is the base UI text size. */
  --spacing-control: var(--shiso-control);
  --text-sm: var(--shiso-text-base);
  --text-sm--line-height: 1.45;
  --shadow-card: var(--shiso-shadow);
}
`;
writeFileSync(join(root, "packages/tailwind/theme.css"), tw);

// ---------- React Native ----------
const tsColors = (set) => Object.entries(set).map(([k, v]) => `    ${camel(k)}: "${hex(v)}",`).join("\n");
const tsNums = (o, indent = "  ") => Object.entries(o).map(([k, v]) => `${indent}${/^\d/.test(k) ? `"${k}"` : camel(k)}: ${JSON.stringify(v)},`).join("\n");
const ts = `// ${HEADER}
export const colors = {
  light: {
${tsColors(light)}
  },
  dark: {
${tsColors(dark)}
  },
} as const;
export const fonts = {
  regular: "HankenGrotesk-Regular",
  medium: "HankenGrotesk-Medium",
  semibold: "HankenGrotesk-SemiBold",
  bold: "HankenGrotesk-Bold",
  mono: "JetBrainsMono-Regular",
  monoMedium: "JetBrainsMono-Medium",
} as const;
export const text = {
${tsNums(text)}
} as const;
export const radius = {
${tsNums(t.radius)}
} as const;
export const space = {
${tsNums(t.space)}
} as const;
export const density = {
${Object.entries(density).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
} as const;
export const shadow = {
  light: ${JSON.stringify(t.shadow.light)},
  darkRingAlpha: ${t.shadow["dark-ring-alpha"]},
} as const;
export type Mode = keyof typeof colors;
export type ColorName = keyof typeof colors.light;
export type Density = keyof typeof density;
`;
writeFileSync(join(root, "packages/native/src/tokens.ts"), ts);

// ---------- Rust ----------
const rsPalette = (set) =>
  Object.entries(set).map(([k, v]) => `    ${k.replace(/-/g, "_")}: [${toRgb(v).join(", ")}],`).join("\n");
const rsF = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rs = `// ${HEADER}

/// One mode's colors as sRGB bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Palette {
${Object.keys(light).map((k) => `    pub ${k.replace(/-/g, "_")}: [u8; 3],`).join("\n")}
}

pub const LIGHT: Palette = Palette {
${rsPalette(light)}
};

pub const DARK: Palette = Palette {
${rsPalette(dark)}
};

/// Sizes that change with density, in logical pixels.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Density {
    pub control: f32,
    pub text: f32,
    pub pad: f32,
    pub gap: f32,
}

${Object.entries(density).map(([k, v]) => `pub const ${upper(k)}: Density = Density { control: ${rsF(v.control)}, text: ${rsF(v.text)}, pad: ${rsF(v.pad)}, gap: ${rsF(v.gap)} };`).join("\n")}

${Object.entries(text).map(([k, v]) => `pub const TEXT_${upper(k)}: f32 = ${rsF(v)};`).join("\n")}

${Object.entries(t.radius).map(([k, v]) => `pub const RADIUS_${upper(k)}: f32 = ${rsF(v)};`).join("\n")}

${Object.entries(t.space).map(([k, v]) => `pub const SPACE_${k}: f32 = ${rsF(v)};`).join("\n")}

pub const FONT_SANS: &str = "${t.font.sans}";
pub const FONT_MONO: &str = "${t.font.mono}";
`;
writeFileSync(join(root, "crates/shiso-theme/src/tokens.rs"), rs);

console.log("tokens built: css, tailwind, native, rust");

// ---------- single-file CSS for pages without a build step ----------
const components = readFileSync(join(root, "packages/css/components.css"), "utf8");
writeFileSync(join(root, "packages/css/shiso.css"), css + "\n" + components);
